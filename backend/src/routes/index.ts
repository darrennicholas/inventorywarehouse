import { Router } from "express";
import healthRoutes from "../modules/health/health.routes.ts";
import authRoutes from "../modules/auth/auth.routes.ts";
import productRoutes from "../modules/products/product.routes.ts";
import categoryRoutes from "../modules/categories/category.routes.ts";
import brandRoutes from "../modules/brands/brand.routes.ts";
import unitRoutes from "../modules/units/unit.routes.ts";
import warehouseRoutes from "../modules/warehouses/warehouse.routes.ts";
import staffRoutes from "../modules/staff/staff.routes.ts";
import customerRoutes from "../modules/customers/customer.routes.ts";
import supplierRoutes from "../modules/suppliers/supplier.routes.ts";
import operationsRoutes from "../modules/operations/operations.routes.ts";
import returnRoutes from "../modules/returns/return.routes.ts";
import fulfillmentRoutes from "../modules/fulfillment/fulfillment.routes.ts";
import userRoutes from "../modules/users/user.routes.ts";
import roleRoutes from "../modules/roles/role.routes.ts";
import auditRoutes from "../modules/audit/audit.routes.ts";
import stockOpnameRoutes from "../modules/stock-opnames/stock-opname.routes.ts";
import notificationRoutes from "../modules/notifications/notification.routes.ts";
import attachmentRoutes from "../modules/attachments/attachment.routes.ts";
import approvalPolicyRoutes from "../modules/approvals/approval-policy.routes.ts";
import { requireAllowedOrigin, requireAuth, requireCsrf, requirePermission, protectModule } from "../middlewares/auth.middleware.ts";
import { requireIdempotency } from "../middlewares/idempotency.middleware.ts";

const router = Router();
router.use(healthRoutes);
router.use("/auth", authRoutes);
router.use(requireAllowedOrigin, requireAuth, requireCsrf);
router.use(requireIdempotency);
router.use("/users", requirePermission("users.manage"), userRoutes);
router.use("/roles", requirePermission("roles.manage"), roleRoutes);
router.use("/products", protectModule("products"), productRoutes);
router.use("/categories", protectModule("categories"), categoryRoutes);
router.use("/brands", protectModule("brands"), brandRoutes);
router.use("/units", protectModule("units"), unitRoutes);
router.use("/warehouses", protectModule("warehouses"), warehouseRoutes);
router.use("/staff", protectModule("staff"), staffRoutes);
router.use("/customers", protectModule("customers"), customerRoutes);
router.use("/suppliers", protectModule("suppliers"), supplierRoutes);
router.use("/operations", operationsRoutes);
router.use("/returns", returnRoutes);
router.use("/fulfillment", fulfillmentRoutes);
router.use("/audit-logs", auditRoutes);
router.use("/stock-opnames", stockOpnameRoutes);
router.use("/notifications", notificationRoutes);
router.use("/attachments", attachmentRoutes);
router.use("/approval-policies", approvalPolicyRoutes);
export default router;
